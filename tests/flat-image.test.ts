import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';
import { decodeFlatImage } from '../src/sources/flat-image';

const fixtureDir = new URL('./browser/fixtures/flat-images/', import.meta.url);

function realFile(name: string): File {
  const bytes = readFileSync(fileURLToPath(new URL(name, fixtureDir)));
  return new File([bytes], name);
}

// PNG decode needs createImageBitmap/OffscreenCanvas (no Node equivalent);
// covered end-to-end in tests/browser/flat-image.spec.ts instead. TIFF decode
// is pure JS (UTIF.js operates on the raw ArrayBuffer) and runs here directly
// against a real 2-page grayscale TIFF generated by Pillow (see that file's
// provenance comment in the fixture directory).
it('decodes a real multi-page grayscale TIFF into one channel per page', async () => {
  const image = await decodeFlatImage(realFile('sample.tiff'));
  expect(image.kind).toBe('channels');
  if (image.kind !== 'channels') return;
  expect(image.width).toBe(8);
  expect(image.height).toBe(8);
  expect(image.channels).toHaveLength(2);
  expect(image.channelNames).toEqual(['Page 0', 'Page 1']);
  // Page 0 was generated as (x*32)%256 per column; page 1 is its 255-complement.
  const page0 = image.channels[0],
    page1 = image.channels[1];
  expect(page0[0]).toBe(0);
  expect(page0[7]).toBe(224);
  expect(page1[0]).toBe(255);
  expect(page1[7]).toBe(31);
});

it('rejects an unsupported extension instead of guessing a format', async () => {
  await expect(decodeFlatImage(new File([new Uint8Array(4)], 'scan.bmp'))).rejects.toThrow(
    /Unsupported image format/,
  );
});

it('rejects a corrupt/non-TIFF file read through the .tiff extension honestly', async () => {
  await expect(
    decodeFlatImage(new File([new Uint8Array([1, 2, 3, 4])], 'not-really-a.tiff')),
  ).rejects.toThrow();
});
